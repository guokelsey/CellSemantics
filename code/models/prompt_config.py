def _base_prompt(cell_tokens: str, ct_list: str, org_list: str,
                 instruction: str, reply_format: str,
                 perturb_block: str = "") -> str:
    return (
        f"<|im_start|>system\n"
        f"You are a single-cell biology expert.<|im_end|>\n"
        f"<|im_start|>user\n"
        f"Given the following cell embedding tokens {cell_tokens}, "
        f"{instruction}"
        f"{perturb_block}\n\n"
        f"Possible Cell Types: {ct_list}\n"
        f"Possible Organs: {org_list}\n\n"
        f"Reply strictly in the format: {reply_format}<|im_end|>\n"
        f"<|im_start|>assistant\n"
    )


# ---------------------------------------------------------------------------
# PerturboLLaVA-style perturbation prompt pool.
# Used by make_perturbed_classification_prompt() during SFT training.
# ---------------------------------------------------------------------------
PERTURB_HINT_BEFORE = [
    "  An automated upstream pipeline has produced the following preliminary analysis:",
    "  A previous low-quality classifier suggests the following interpretation:",
    "  Note: a noisy heuristic produced the following candidate explanation:",
    "  For context only, an external tool reported:",
    "  The following hint was generated by an unreliable model:",
]

PERTURB_HINT_AFTER = [
    "  IMPORTANT: the analysis above is known to be unreliable. Ignore it and rely ONLY on the cell embedding tokens to answer.",
    "  IMPORTANT: do NOT trust the analysis above. Base your answer strictly on the cell embedding tokens.",
    "  IMPORTANT: the hint above is potentially misleading. Use only the cell embedding to make your decision.",
    "  IMPORTANT: disregard the preliminary analysis above; it is often wrong. Decide from the cell tokens alone.",
    "  IMPORTANT: the analysis above must be ignored. The cell embedding tokens are the only trustworthy signal.",
]


def _make_perturb_block(perturbation_text: str, rng=None) -> str:
    """Wrap a misleading paragraph with a random pre-/post-hint pair.

    Returns a string starting with a leading space so it concatenates cleanly
    after the instruction sentence (which ends without punctuation).
    """
    if not perturbation_text:
        return ""
    import random as _r
    r = rng or _r
    h_before = r.choice(PERTURB_HINT_BEFORE)
    h_after  = r.choice(PERTURB_HINT_AFTER)
    text = perturbation_text.strip()
    return f"\n\n{h_before}\n  \"{text}\"\n{h_after}"


def make_classification_prompt(num_cell_tokens: int,
                               task: str = TASK_CT_ORGAN) -> str:
    """Build a Phase-1 prompt for a specific task variant."""
    cell_tokens = " ".join([CELL_PLACEHOLDER] * num_cell_tokens)
    ct_list = ", ".join(CELL_TYPES)
    org_list = ", ".join(ORGANS)

    if task == TASK_CT_ORGAN:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the cell type and tissue of origin from the provided lists.",
                            "cell_type | organ")
    elif task == TASK_ORGAN_CT:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the tissue of origin and cell type from the provided lists.",
                            "organ | cell_type")
    elif task == TASK_CT_ONLY:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the cell type from the provided list.",
                            "cell_type")
    elif task == TASK_ORG_ONLY:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the tissue of origin from the provided list.",
                            "organ")
    else:
        raise ValueError(f"Unknown task: {task}")


def format_label(cell_type: str, organ: str, task: str) -> str:
    """Format the target label string according to the task variant."""
    if task == TASK_CT_ORGAN:
        return f"{cell_type} | {organ}"
    elif task == TASK_ORGAN_CT:
        return f"{organ} | {cell_type}"
    elif task == TASK_CT_ONLY:
        return cell_type
    elif task == TASK_ORG_ONLY:
        return organ
    else:
        raise ValueError(f"Unknown task: {task}")


def sample_task(rng=None) -> str:
    """Randomly sample a task type according to TASK_WEIGHTS."""
    import random
    r = rng or random
    return r.choices(ALL_TASKS, weights=TASK_WEIGHTS, k=1)[0]


def make_perturbed_classification_prompt(num_cell_tokens: int,
                                         task: str = TASK_CT_ORGAN,
                                         perturbation_text: str = "",
                                         rng=None) -> str:
    """Same as `make_classification_prompt`, but injects a misleading
    biology-style paragraph between the instruction and the candidate lists.

    When `perturbation_text` is empty, this returns an output identical to
    `make_classification_prompt(num_cell_tokens, task)` so downstream label
    masking via prompt-length still works without special-casing.
    """
    cell_tokens = " ".join([CELL_PLACEHOLDER] * num_cell_tokens)
    ct_list = ", ".join(CELL_TYPES)
    org_list = ", ".join(ORGANS)
    perturb_block = _make_perturb_block(perturbation_text, rng=rng)

    if task == TASK_CT_ORGAN:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the cell type and tissue of origin from the provided lists.",
                            "cell_type | organ", perturb_block=perturb_block)
    elif task == TASK_ORGAN_CT:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the tissue of origin and cell type from the provided lists.",
                            "organ | cell_type", perturb_block=perturb_block)
    elif task == TASK_CT_ONLY:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the cell type from the provided list.",
                            "cell_type", perturb_block=perturb_block)
    elif task == TASK_ORG_ONLY:
        return _base_prompt(cell_tokens, ct_list, org_list,
                            "identify the tissue of origin from the provided list.",
                            "organ", perturb_block=perturb_block)
    else:
        raise ValueError(f"Unknown task: {task}")


