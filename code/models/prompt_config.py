def format_grn_label(grn_target) -> str:
    """Normalize GRN labels into the scPilot-style target format."""
    if grn_target is None:
        return ""
    if isinstance(grn_target, str):
        return grn_target.strip()
    if isinstance(grn_target, dict):
        direct = (
            grn_target.get("answer")
            or grn_target.get("response")
            or grn_target.get("formatted_label")
        )
        if direct:
            return str(direct).strip()
        reasoning = (
            grn_target.get("reasoning")
            or grn_target.get("rationale")
            or "Regulatory evidence is provided by the cell context."
        )
        possibility = (
            grn_target.get("possibility")
            or grn_target.get("probability")
            or grn_target.get("score")
        )
        if possibility is None and "label" in grn_target:
            possibility = 1.0 if int(grn_target["label"]) == 1 else 0.0
        if possibility is not None:
            return f"Reasoning: {reasoning}\nPossibility is: {possibility}"
    return str(grn_target).strip()


def format_grn_binary_label(grn_target) -> str:
    """Normalize GRN labels into a strict 1/0 target for binary training."""
    if grn_target is None:
        return ""
    if isinstance(grn_target, dict):
        direct = (
            grn_target.get("answer")
            or grn_target.get("response")
            or grn_target.get("formatted_label")
        )
        if isinstance(direct, str) and direct.strip() in {"0", "1"}:
            return direct.strip()
        possibility = (
            grn_target.get("possibility")
            or grn_target.get("probability")
            or grn_target.get("score")
        )
        if possibility is None and "label" in grn_target:
            possibility = grn_target["label"]
        if possibility is not None:
            return "1" if float(possibility) >= 0.5 else "0"
    if isinstance(grn_target, (int, float)):
        return "1" if float(grn_target) >= 0.5 else "0"
    text = str(grn_target).strip()
    if text in {"0", "1"}:
        return text
    lower = text.lower()
    if "possibility is:" in lower:
        try:
            value = lower.split("possibility is:", 1)[1].strip().split()[0]
            return "1" if float(value) >= 0.5 else "0"
        except Exception:
            pass
    if lower in {"true", "yes", "positive", "pos"}:
        return "1"
    if lower in {"false", "no", "negative", "neg"}:
        return "0"
    return text


CONFLICT_QUESTION_POOL = [
    "An automated pipeline labelled this cell as **{wrong_ct} | {wrong_org}**, "
    "but I do not trust the label. Look at the cell tokens and tell me what "
    "this cell ACTUALLY is. If the suggestion is wrong, correct it.",
    "I have a hypothesis: this cell is a {wrong_ct} from {wrong_org}. "
    "Verify or refute it from the cell embedding tokens.",
    "A colleague claims this is **{wrong_ct} | {wrong_org}**. "
    "Read the cell tokens and tell me whether the claim is correct, and "
    "if not, what the correct identity is.",
]

CONFLICT_REPLY_HINT_POOL = [
    "Reply on a single line in the format: cell_type | organ.",
    "Output exactly one line: cell_type | organ -- the cell's TRUE identity "
    "according to the embedding, not according to my hint.",
    "Answer with: cell_type | organ.",
]


def make_conflict_prompt(num_cell_tokens: int,
                         wrong_cell_type: str,
                         wrong_organ: str,
                         rng=None) -> str:
    """Inject a deliberately wrong cell-type/organ suggestion. The target is
    the TRUE label (built outside, identical to standard tasks), so the
    model must learn to ignore the misleading text whenever it conflicts
    with the cell-token evidence.
    """
    import random as _r
    r = rng or _r
    cell_tokens = " ".join([CELL_PLACEHOLDER] * num_cell_tokens)
    sys_msg  = r.choice(FREEFORM_SYSTEM_POOL)
    question = r.choice(CONFLICT_QUESTION_POOL).format(
        wrong_ct=wrong_cell_type, wrong_org=wrong_organ)
    reply    = r.choice(CONFLICT_REPLY_HINT_POOL)
    body = (f"Cell embedding tokens: {cell_tokens}\n\n{question}")
    return (
        f"<|im_start|>system\n{sys_msg}<|im_end|>\n"
        f"<|im_start|>user\n{body}\n\n{reply}<|im_end|>\n"
        f"<|im_start|>assistant\n"
    )


def sample_wrong_label(true_ct: str, true_org: str, rng=None,
                       wrong_ct_prob: float = 0.7,
                       wrong_org_prob: float = 0.7):
    """Sample a (wrong_ct, wrong_org) pair guaranteed to differ from the
    truth on at least one axis. By default both axes are independently
    perturbed with prob 0.7, so most samples have BOTH wrong, which makes
    the conflict signal stronger.
    """
    import random as _r
    r = rng or _r
    candidates_ct = [c for c in CELL_TYPES if c != true_ct]
    candidates_org = [o for o in ORGANS if o != true_org]
    wrong_ct = r.choice(candidates_ct) if r.random() < wrong_ct_prob else true_ct
    wrong_org = r.choice(candidates_org) if r.random() < wrong_org_prob else true_org
    if wrong_ct == true_ct and wrong_org == true_org:
        # Force at least one disagreement.
        wrong_ct = r.choice(candidates_ct)
    return wrong_ct, wrong_org


