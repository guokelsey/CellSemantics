# ===========================================================================
# v18 -- Evidence-driven tasks (Top-Gene prediction + Conflict correction).
#
# Goal
# ----
# Stop the model from solving SFT by memorising (cell_id -> label). Force it
# to actually READ what is encoded inside the cell tokens by introducing
# tasks whose target cannot be reconstructed from the cell-type label alone.
#
#   1. Top-Gene prediction:
#        Prompt asks for the K most highly expressed genes in THIS cell.
#        Target = the actual gene symbols (top-K by count) for THIS cell.
#        These are different for every cell of the same type (donor/state
#        variation), so no shortcut via the label exists.
#
#   2. Conflict correction:
#        The user prompt contains a deliberately WRONG cell-type/organ
#        suggestion. The model must compare the suggestion against the cell
#        tokens and flag the inconsistency, then output the correct identity
#        and an evidence-based justification.
#        This directly attacks the "follow the text, ignore the modality"
#        failure mode visible in v17 open inference.
# ===========================================================================

